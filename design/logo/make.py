"""Writes every Anon Player brand file from the numbers below and traced.json (the hooded figure).
Icon = rounded play triangle with two almond eye slits (geometry here). Brand figure = hood (traced).
Change a number and rerun: SVGs, Android adaptive/themed icon, animated splash, store PNGs, previews all follow.
Usage: python design/logo/make.py      (needs ImageMagick `magick` for the PNGs)"""
import json, math, pathlib, subprocess

L = pathlib.Path(__file__).resolve().parent
RES = L.parents[1] / "app/src/main/res"
BG, FG = "#26282D", "#FFFFFF"                  # charcoal + white, the Anon family colours
N = 613                                        # design square = the visible icon (72 of the 108 adaptive units)
K = 72 / N                                     # design units -> 108 grid
OFF = 18                                       # (108 - 72) / 2

# ---- the icon: rounded triangle + almond eyes (design units, measured from the chosen reference)
TRI = [(167, 107), (167, 504), (515, 305.5)]   # top-left, bottom-left, tip
R = 46                                         # corner rounding
EYES = [(247, 298, -9), (383, 298, 9)]         # centre x, y, tilt in degrees (outer corners up)
EYE_W, EYE_H = 84, 44


def rounded_poly(pts, r):
    out = []
    n = len(pts)
    for i in range(n):
        p, a, b = pts[i], pts[i - 1], pts[(i + 1) % n]
        def toward(q):
            dx, dy = q[0] - p[0], q[1] - p[1]
            d = math.hypot(dx, dy)
            return (p[0] + dx / d * r, p[1] + dy / d * r)
        s, e = toward(a), toward(b)
        out.append(("L" if out else "M") + f"{s[0]:.1f},{s[1]:.1f} Q{p[0]},{p[1]} {e[0]:.1f},{e[1]:.1f}")
    return " ".join(out) + " Z"


def almond(cx, cy, tilt):
    t = math.radians(tilt)
    def rot(x, y):
        return (cx + x * math.cos(t) - y * math.sin(t), cy + x * math.sin(t) + y * math.cos(t))
    a, b = rot(-EYE_W / 2, 0), rot(EYE_W / 2, 0)
    c1, c2 = rot(0, -EYE_H), rot(0, EYE_H)   # quadratic controls: curve peaks at EYE_H/2
    return f"M{a[0]:.1f},{a[1]:.1f} Q{c1[0]:.1f},{c1[1]:.1f} {b[0]:.1f},{b[1]:.1f} Q{c2[0]:.1f},{c2[1]:.1f} {a[0]:.1f},{a[1]:.1f} Z"


TRI_D = rounded_poly(TRI, R)
EYES_D = " ".join(almond(*e) for e in EYES)
ICON_D = TRI_D + " " + EYES_D                  # even-odd: the eyes are holes
TRI_C = ((TRI[0][0] + TRI[2][0]) / 2, (TRI[0][1] + TRI[1][1]) / 2)  # triangle bbox centre: pivot for the splash

# ---- the hood (traced, 1024 square) and where its small play sat (measured: x 466-595, y 413-541)
T = json.loads((L / "traced.json").read_text())
HN = T["hood_size"]
HOOD_PLAY = ((466 + 595) / 2, (413 + 541) / 2, 541 - 413)   # centre x, y, height in hood units
H2D = N / HN                                                   # hood units -> design units
START_S = HOOD_PLAY[2] * H2D / (TRI[1][1] - TRI[0][1])        # icon scale that fits the hood's face
START_X, START_Y = HOOD_PLAY[0] * H2D, HOOD_PLAY[1] * H2D


def hood_g(fill, extra=""):
    return f'<g{extra}><g transform="scale({H2D:.5f}) {T["hood"]["transform"]}"><path fill="{fill}" fill-rule="evenodd" d="{T["hood"]["d"]}"/></g></g>'


def icon_path(fill):
    return f'<path fill="{fill}" fill-rule="evenodd" d="{ICON_D}"/>'


def svg(body, rx=None, bg=None, note=""):
    back = f'<rect width="{N}" height="{N}"{f" rx={chr(34)}{rx}{chr(34)}" if rx else ""} fill="{bg}"/>' if bg else ""
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {N} {N}" width="512" height="512">\n'
            f'<!-- Anon Player: {note}. Generated by design/logo/make.py -->\n{back}{body}</svg>\n')


files = {
    "anon-player-logo.svg": svg(icon_path(FG), rx=110, bg=BG, note="app icon, rounded square"),
    "anon-player-square.svg": svg(icon_path(FG), bg=BG, note="full bleed square for stores that apply their own mask"),
    "anon-player-mark.svg": svg(icon_path(FG), note="mark only, transparent"),
    "anon-player-monochrome.svg": svg(icon_path("#000"), note="one-colour mark (themed icons, notifications)"),
    "anon-player-hood.svg": svg(hood_g(FG), rx=110, bg=BG, note="brand figure: the hood"),
    "anon-player-mark-dark.svg": svg(icon_path(BG), note="bare mark, charcoal, for light backgrounds"),
    "anon-player-hood-mark.svg": svg(hood_g(FG), note="bare hood, white, transparent"),
}
for n, s in files.items():
    (L / n).write_text(s)


# ---- Android: adaptive + themed icon, and the animated splash (AVD) on the same 108 grid
def vd(body, extra_ns=""):
    return ('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by design/logo/make.py -->\n'
            f'<vector xmlns:android="http://schemas.android.com/apk/res/android"{extra_ns}\n'
            '    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">\n'
            f'{body}</vector>\n')


def grid(inner, name=""):
    nm = f' android:name="{name}"' if name else ""
    return (f'    <group{nm} android:translateX="{OFF}" android:translateY="{OFF}">\n'
            f'      <group android:scaleX="{K:.5f}" android:scaleY="{K:.5f}">\n{inner}      </group>\n    </group>\n')


def vd_path(d, fill, name=""):
    nm = f' android:name="{name}"' if name else ""
    return f'        <path{nm} android:fillColor="{fill}" android:fillType="evenOdd" android:pathData="{d}"/>\n'


for d in ("drawable", "mipmap-anydpi-v26", "values", "values-v31", "animator"):
    (RES / d).mkdir(parents=True, exist_ok=True)
(RES / "drawable/ic_launcher_foreground.xml").write_text(vd(grid(vd_path(ICON_D, FG))))
(RES / "drawable/ic_launcher_monochrome.xml").write_text(vd(grid(vd_path(ICON_D, "#FF000000"))))
(RES / "values/ic_launcher_background.xml").write_text(
    f'<?xml version="1.0" encoding="utf-8"?>\n<resources>\n    <color name="ic_launcher_background">{BG}</color>\n</resources>\n')
adaptive = ('<?xml version="1.0" encoding="utf-8"?>\n<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
            '    <background android:drawable="@color/ic_launcher_background"/>\n'
            '    <foreground android:drawable="@drawable/ic_launcher_foreground"/>\n'
            '    <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>\n</adaptive-icon>\n')
for n in ("ic_launcher.xml", "ic_launcher_round.xml"):
    (RES / "mipmap-anydpi-v26" / n).write_text(adaptive)

# Splash timeline (ms), kept under 1 s: hood fades in -> the small play in its face grows into the icon while the
# hood fades away -> the eyes blink once. Groups: hood (alpha+scale), play (scale+move), lids (scaleY).
DUR = 950
hood_vd = (f'        <group android:name="hood" android:pivotX="{N / 2}" android:pivotY="{N / 2}">\n'
           f'          <group android:scaleX="{H2D:.5f}" android:scaleY="{H2D:.5f}">\n'
           f'            <group android:translateY="{HN}" android:scaleX="0.1" android:scaleY="-0.1">\n'
           f'              <path android:name="hoodPath" android:fillColor="{FG}" android:fillAlpha="0" android:fillType="evenOdd" android:pathData="{T["hood"]["d"]}"/>\n'
           '            </group>\n          </group>\n        </group>\n')
cx, cy = TRI_C


def eyes_vd(prefix, closed):
    return "".join(f'          <group android:name="{prefix}{i}" android:pivotX="{e[0]}" android:pivotY="{e[1]}"{" android:scaleY=\"0\"" if closed else ""}>\n'
                   f'            <path android:fillColor="{BG}" android:pathData="{almond(*e)}"/>\n          </group>\n'
                   for i, e in enumerate(EYES))


play_vd = (f'        <group android:name="play" android:pivotX="{cx}" android:pivotY="{cy}"'
           f' android:translateX="{START_X - cx:.1f}" android:translateY="{START_Y - cy:.1f}"'
           f' android:scaleX="{START_S:.4f}" android:scaleY="{START_S:.4f}">\n'
           + vd_path(TRI_D, FG) + eyes_vd("eye", closed=True)
           + '        </group>\n')
(RES / "drawable/splash_icon.xml").write_text(vd(grid(hood_vd + play_vd)))


def anim(prop, a, b, start, dur, interp="fast_out_slow_in", typ="floatType"):
    return (f'    <objectAnimator android:propertyName="{prop}" android:valueFrom="{a}" android:valueTo="{b}"'
            f' android:startOffset="{start}" android:duration="{dur}" android:valueType="{typ}"'
            f' android:interpolator="@android:interpolator/{interp}"/>\n')


def animset(*items):
    return ('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by design/logo/make.py -->\n'
            '<set xmlns:android="http://schemas.android.com/apk/res/android" android:ordering="together">\n'
            + "".join(items) + '</set>\n')


